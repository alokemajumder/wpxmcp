#!/usr/bin/env node
/**
 * Writes docs/TOOLS.md from the built toolset, so the reference can never drift
 * from the code. Run after `npm run build`; CI fails when the committed file is stale.
 *
 * Companion-plugin requirements are read from each handler's compiled source:
 * a handler that calls one of the "require the plugin" helpers cannot run
 * without it, and one that only asks hasHelperPlugin() works either way.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = (p) => path.join(root, "dist", p);

const { installNodePlatform } = await import(dist("platform-node.js"));
const { SiteRegistry } = await import(dist("lib/registry.js"));
const { listSkills } = await import(dist("lib/skills.js"));
installNodePlatform();
const ctx = { registry: new SiteRegistry({ sites: [], source: "docs" }) };

const GROUPS = [
  ["Playbooks", "tools/skills.js", "skillTools", "Load one before substantive work — they encode what the API alone does not tell you."],
  ["Multi-site", "tools/sites.js", "siteTools"],
  ["Content", "tools/content.js", "contentTools"],
  ["Taxonomies", "tools/taxonomy.js", "taxonomyTools"],
  ["Media", "tools/media.js", "mediaTools"],
  ["Users", "tools/users.js", "userTools"],
  ["Comments", "tools/comments.js", "commentTools"],
  ["Plugins", "tools/plugins.js", "pluginTools"],
  ["Operating installed plugins", "tools/plugin-control.js", "pluginControlTools", "Settings, admin screens and forms of any installed plugin, operated the way an administrator would in wp-admin."],
  ["Themes", "tools/themes.js", "themeTools"],
  ["Theme development", "tools/themedev.js", "themeDevTools"],
  ["Appearance", "tools/appearance.js", "appearanceTools"],
  ["Site configuration", "tools/site.js", "siteConfigTools"],
  ["Operations and security", "tools/ops.js", "opsTools"],
  ["Performance profiling", "tools/profiler.js", "profilerTools"],
  ["Developer introspection", "tools/devtools.js", "devTools"],
  ["SEO, content and fleet", "tools/growth.js", "growthTools"],
  ["Power tools", "tools/power.js", "powerTools"],
  ["Bulk and audit", "tools/bulk.js", "bulkTools"],
];

const REQUIRES = /\b(requireHelper|requireHelperNamespace|helper)\(\s*client/;
const ENHANCED = /hasHelperPlugin\(/;

function firstSentence(text) {
  const s = String(text).replace(/\s+/g, " ").trim();
  const m = /^(.+?[.!?])(\s|$)/.exec(s);
  return (m ? m[1] : s).replace(/\|/g, "\\|");
}

let total = 0, required = 0, enhanced = 0, destructive = 0;
const sections = [];
for (const [title, file, factory, intro] of GROUPS) {
  let tools;
  try {
    tools = (await import(dist(file)))[factory](ctx);
  } catch {
    continue;
  }
  if (!tools.length) continue;
  const rows = tools.map((t) => {
    const src = t.handler.toString();
    const marks = [];
    const companion = t.companion ?? (REQUIRES.test(src) ? "required" : ENHANCED.test(src) ? "enhanced" : undefined);
    if (companion === "required") { marks.push("🔌"); required++; }
    else if (companion === "enhanced") { marks.push("➕"); enhanced++; }
    if (t.destructive) { marks.push("⚠️"); destructive++; }
    else if (t.readOnly) marks.push("👁");
    total++;
    return `| \`${t.name}\` | ${marks.join(" ")} | ${firstSentence(t.description)} |`;
  });
  sections.push(`## ${title} (${tools.length})\n\n${intro ? intro + "\n\n" : ""}| Tool | | Purpose |\n| --- | --- | --- |\n${rows.join("\n")}`);
}

const skills = listSkills().map((s) => `| \`${s.name}\` | ${s.description.replace(/\|/g, "\\|")} |`).join("\n");

const doc = `# Tool reference

<!-- Generated by scripts/gen-tools-doc.mjs from the built toolset. Do not edit by hand. -->

**${total} tools.** Every tool that acts on a site accepts an optional **\`site_id\`**; with one site configured it can be omitted.

| Mark | Meaning |
| --- | --- |
| 🔌 | Needs the [companion plugin](COMPANION_PLUGIN.md) — ${required} tools. Core WordPress has no REST route for what they do |
| ➕ | Works on stock WordPress, returns more with the companion plugin — ${enhanced} tools |
| ⚠️ | Destructive: previews first and needs a \`confirm_token\` or explicit confirmation — ${destructive} tools |
| 👁 | Read-only |

${total - required} of ${total} tools work against a stock WordPress install with nothing added.

---

${sections.join("\n\n---\n\n")}

---

## Bundled playbooks (${listSkills().length})

\`load_skill\` routes a plain-language description of the task to one of these.

| Playbook | When it applies |
| --- | --- |
${skills}
`;

const out = path.join(root, "docs", "TOOLS.md");
fs.writeFileSync(out, doc);
console.log(`Wrote docs/TOOLS.md — ${total} tools, ${required} need the companion plugin, ${destructive} destructive.`);
